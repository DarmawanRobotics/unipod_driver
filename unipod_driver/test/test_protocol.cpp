TEST(Protocol, EncodeMatchesDocumentExamples)
{
  for (const auto & e : examples()) {
    EXPECT_EQ(encode(e.cmd, e.payload, 0, true), e.expected) << e.name;
  }
}

TEST(Protocol, ParserDecodesDocumentExamples)
{
  for (const auto & e : examples()) {
    FrameParser p;
    std::vector<Frame> frames;
    p.push(e.expected.data(), e.expected.size(), [&](const Frame & f) {frames.push_back(f);});
    ASSERT_EQ(frames.size(), 1u) << e.name;
    EXPECT_EQ(frames[0].cmd, e.cmd) << e.name;
    EXPECT_EQ(frames[0].payload, e.payload) << e.name;
    EXPECT_EQ(frames[0].ctrl, 0x01) << e.name;
  }
}

TEST(Protocol, SequenceNumberIsLittleEndian)
{
  const auto f = encode(0x01, {}, 0x1234);
  EXPECT_EQ(f[5], 0x34);
  EXPECT_EQ(f[6], 0x12);
}

TEST(Protocol, ParserResyncsAcrossGarbageSplitsAndBadCrc)
{
  const Bytes a = encode(0x18, {0x07, 0x05}, 1, false);
  Bytes b = encode(0x0D, Bytes(12, 0x11), 2, false);
  Bytes bad = encode(0x10, {0x00, 0x02}, 3, false);
  bad.back() ^= 0xFF;

  Bytes stream = {0x00, 0x55, 0x13, 0x66};  // noise, including a lone 0x55
  stream.insert(stream.end(), a.begin(), a.end());
  stream.insert(stream.end(), bad.begin(), bad.end());
  stream.insert(stream.end(), b.begin(), b.end());

  FrameParser p;
  std::vector<Frame> frames;
  // one byte at a time: worst case for reassembly
  for (uint8_t byte : stream) {
    p.push(&byte, 1, [&](const Frame & f) {frames.push_back(f);});
  }
  ASSERT_EQ(frames.size(), 2u);
  EXPECT_EQ(frames[0].cmd, 0x18);
  EXPECT_EQ(frames[0].seq, 1);
  EXPECT_EQ(frames[1].cmd, 0x0D);
  EXPECT_EQ(frames[1].payload.size(), 12u);
  EXPECT_EQ(p.crcErrors(), 1u);
}

TEST(Protocol, ParserRejectsAbsurdLength)
{
  // STX followed by a length far above any MT11 reply, then a real frame.
  Bytes stream = {0x55, 0x66, 0x02, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00};
  const auto good = encode(0x1A, {0x03}, 7, false);
  stream.insert(stream.end(), good.begin(), good.end());
  FrameParser p;
  std::vector<Frame> frames;
  p.push(stream.data(), stream.size(), [&](const Frame & f) {frames.push_back(f);});
  ASSERT_EQ(frames.size(), 1u);
  EXPECT_EQ(frames[0].cmd, 0x1A);
}
